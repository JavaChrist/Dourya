/** Plain-text footer, same content as the HTML footer. */
export function textFooter(
  { origin, legal, unsubscribeUrl }: BaseEmailProps,
  reason: string,
): string {
  const lines = [
    "--",
    reason,
    [
      orMissing(legal.name, "EMAIL_LEGAL_NAME"),
      orMissing(legal.address, "EMAIL_LEGAL_ADDRESS"),
      legal.registration,
    ]
      .filter(Boolean)
      .join(" · "),
    origin,
  ];
  if (unsubscribeUrl) lines.push(`Se désinscrire : ${unsubscribeUrl}`);
  return lines.join("\n");
}
