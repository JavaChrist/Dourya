export type PlaceOrderInput = {
  /** Generated by the browser for one cart + address + shipping: same key = same order. */
  attemptKey: string;
  items: unknown;
  email: unknown;
  address: Record<string, unknown>;
  rateId: unknown;
  acceptTerms: unknown;
  /** Total the customer saw. A different server total = the cart changed meanwhile. */
  expectedTotalCents: unknown;
};

export type PlaceOrderDeps = {
  stripe: StripeAccess | null;
  products: Product[];
  settings: ShippingSettings;
  customer: { uid: string } | null;
  origin: string;
  /** Test preview switch (see test-preview.ts). Omitted = config values. */
  checkout?: CheckoutSwitch;
  now?: Date;
};

export type PlaceOrderErrorCode =
  | GateReason
  | "login_required"
  | "invalid_form"
  | "cart_empty"
  | "cart_changed"
  | "total_changed"
  | "shipping_unavailable"
  | "out_of_stock"
  | "attempt_conflict"
  | "order_closed"
  | "payment_error";

export type PlaceOrderResult =
  | { kind: "redirect"; url: string }
  | { kind: "error"; code: PlaceOrderErrorCode; fieldErrors?: FieldErrors; resetAttempt?: boolean };

const EMAIL = /^[^\s@]{1,64}@[^\s@]{1,190}\.[^\s@]{2,}$/;

export function returnUrl(origin: string, orderId: string): string {
  return `${origin}/commande/retour?commande=${encodeURIComponent(orderId)}`;
}

const fail = (code: PlaceOrderErrorCode, extra: Omit<Extract<PlaceOrderResult, { kind: "error" }>, "kind" | "code"> = {}): PlaceOrderResult => ({
  kind: "error",
  code,
  ...extra,
});

function logStripeError(event: string, error: unknown) {
  if (error instanceof StripeError)
    logEvent(event, { category: error.category, status: error.status ?? undefined, stripeType: error.detail?.type, stripeCode: error.detail?.code, stripeParam: error.detail?.param });
  else logEvent(event, { category: "unexpected", error: error instanceof Error ? error.name : "unknown" });
}

/**
 * Server checkout: re-prices the cart, re-quotes shipping, creates the order
 * with its stock hold, then the Stripe Checkout Session, and returns where
 * to send the customer. Payment success is never decided here: only a
 * session re-read at Stripe (webhook, return page) marks an order paid.
 */
export async function placeOrder(input: PlaceOrderInput, deps: PlaceOrderDeps): Promise<PlaceOrderResult> {
  return placeOrderOnce(input, deps, true);
}

async function placeOrderOnce(input: PlaceOrderInput, deps: PlaceOrderDeps, mayRestart: boolean): Promise<PlaceOrderResult> {
  const now = deps.now ?? new Date();
  if (!commerceConfig.guestCheckoutEnabled && !deps.customer) return fail("login_required");

  // Form
  const fieldErrors: FieldErrors = {};
  const email = typeof input.email === "string" ? input.email.trim().toLowerCase() : "";
  if (!EMAIL.test(email) || email.length > 254) fieldErrors.email = "Adresse e-mail invalide.";
  const address = validateAddress(input.address);
  if (!address.ok) Object.assign(fieldErrors, address.errors);
  if (input.acceptTerms !== true) fieldErrors.acceptTerms = "Acceptez les conditions générales de vente pour continuer.";
  const rateId = typeof input.rateId === "string" ? input.rateId : "";
  if (!rateId) fieldErrors.rateId = "Choisissez un mode de livraison.";
  if (Object.keys(fieldErrors).length > 0 || !address.ok) return fail("invalid_form", { fieldErrors });
  const { fullName, line1, line2, postalCode, city, country } = address.value;
  const shippingAddress = { fullName, line1, ...(line2 ? { line2 } : {}), postalCode, city, country };

  // Cart, shipping, gate: all recomputed here
  const draft = buildCheckout({ items: input.items, products: deps.products, settings: deps.settings, country: shippingAddress.country, rateId, now });
  if (draft.lines.length === 0) return fail("cart_empty");
  if (draft.cartChanged) return fail("cart_changed", { resetAttempt: true });
  const gate = checkoutGate({ keyMode: deps.stripe?.mode ?? null, hasDemo: draft.cart.hasDemo, ...deps.checkout });
  if (gate || !deps.stripe) return fail(gate ?? "payment_not_configured");
  if (!draft.quote.available || !draft.shipping || draft.totalCents === null) return fail("shipping_unavailable");
  if (draft.totalCents !== input.expectedTotalCents) return fail("total_changed", { resetAttempt: true });
  const stripe = deps.stripe;
  const shippingLabel = draft.shipping.label;

  // Stripe wants expires_at at least 30 minutes after it receives the request:
  // 5 minutes of margin. Only used for a new order; a retry replays the saved value.
  const expiresAt = Math.floor(now.getTime() / 1000) + (Math.max(30, commerceConfig.stockReservationMinutes) + 5) * 60;

  // Opportunistic clean-up of expired holds (no cron): never blocks the checkout.
  try {
    await releaseExpiredReservations((id) => stripe.client.getCheckoutSession(id), now, 10, (id, request) => resolveDraft(stripe, id, request, now));
  } catch (error) {
    logStripeError("checkout_sweep_failed", error);
  }

  const created = await createOrderWithReservation({
    attemptKey: input.attemptKey,
    customerUid: deps.customer?.uid ?? null,
    email,
    lines: draft.lines,
    shipping: draft.shipping,
    shippingAddress,
    subtotalCents: draft.subtotalCents,
    shippingCents: draft.shippingCents,
    totalCents: draft.totalCents,
    holds: draft.holds,
    reservationMinutes: commerceConfig.stockReservationMinutes,
    // Saved with the order before any call to Stripe: every retry of this
    // attempt (lost response, double click, concurrent request) sends exactly
    // this request again, so Stripe answers with the same session.
    paymentRequest: (id) => ({
      idempotencyKey: `${input.attemptKey}-${id}`,
      expiresAt,
      lines: draft.lines.map(toCheckoutLine),
      shipping: { label: shippingLabel, amountCents: draft.shippingCents },
      email,
      successUrl: returnUrl(deps.origin, id),
      cancelUrl: `${deps.origin}/commande`,
    }),
    now,
  });
  if (created.kind === "out_of_stock") return fail("out_of_stock", { resetAttempt: true });
  if (created.kind === "conflict") return fail("attempt_conflict", { resetAttempt: true });
  if (created.kind === "invalid") {
    logEvent("checkout_invalid", { reason: created.reason });
    return fail(created.reason === "attempt_key" ? "attempt_conflict" : "cart_changed", { resetAttempt: true });
  }
  const orderId = created.orderId;
  const back = returnUrl(deps.origin, orderId);

  // Double click: the session already exists, send the customer back to it.
  if (created.kind === "existing" && created.paymentRef) {
    try {
      const existing = await stripe.client.getCheckoutSession(created.paymentRef);
      return { kind: "redirect", url: existing.status === "open" && existing.url ? existing.url : back };
    } catch (error) {
      logStripeError("checkout_payment_reread_failed", error);
      return { kind: "redirect", url: back };
    }
  }

  const request = created.paymentRequest;
  if (!request) {
    // Older draft saved without its request: nothing safe to replay.
    logEvent("checkout_request_missing");
    return fail("payment_error");
  }
  const outcome = await sendStoredRequest(stripe, orderId, request, now, created.kind === "existing");
  if (outcome.kind === "uncertain") {
    // The first request may still have created a session: keep the draft, its
    // hold and its request. No new key is made until Stripe tells us more.
    if (outcome.reviewCode) await flagOrder(orderId, outcome.reviewCode, "checkout", now);
    return fail("payment_error");
  }
  if (outcome.kind === "none") {
    // Proven: this request created no session and can no longer create one.
    // The draft is closed and the same attempt starts a new order (new key).
    await cancelDraft(orderId, now, "payment_request_failed");
    if (!mayRestart) return fail("payment_error");
    return placeOrderOnce(input, deps, false);
  }
  const session = outcome.session;
  // Stripe computes its own total from the lines: it must be ours to the cent.
  // A session already paid or closed has no payment page any more.
  if (session.amountCents !== draft.totalCents || session.currency.toUpperCase() !== "EUR" || session.orderId !== orderId || (session.status === "open" && !session.url)) {
    logEvent("checkout_session_mismatch");
    return fail("payment_error");
  }

  const attached = await attachPayment(orderId, session.id, now);
  if (attached.kind === "refused" && attached.reason === "payment_already_attached") {
    // A concurrent request attached its own session first: follow that one.
    const winner = (await getOrder(orderId))?.paymentRef;
    if (winner) {
      try {
        const other = await stripe.client.getCheckoutSession(winner);
        return { kind: "redirect", url: other.status === "open" && other.url ? other.url : back };
      } catch (error) {
        logStripeError("checkout_payment_reread_failed", error);
      }
    }
    return { kind: "redirect", url: back };
  }
  if (attached.kind === "refused" || attached.kind === "not_found") {
    logEvent("checkout_attach_refused", { reason: attached.kind === "refused" ? attached.reason : "not_found" });
    return fail("order_closed", { resetAttempt: true });
  }
  if (session.status !== "open" || !session.url) {
    // The original session, already paid (or closed) while its response was lost.
    await applyPaymentState(orderId, session, "checkout", now);
    await notifyOrder(orderId, now);
    return { kind: "redirect", url: back };
  }
  logEvent("checkout_payment_created", { order: orderId });
  return { kind: "redirect", url: session.url };
}

/** Stripe keeps an idempotency key at least 24 h: 23 h to stay inside that window. */
const KEY_RETENTION_MS = 23 * 3600_000;

const toSessionInput = (orderId: string, r: StoredPaymentRequest): CreateSessionInput => ({
  orderId,
  lines: r.lines,
  shipping: r.shipping,
  email: r.email,
  successUrl: r.successUrl,
  cancelUrl: r.cancelUrl,
  expiresAt: r.expiresAt,
  idempotencyKey: r.idempotencyKey,
});

type SendOutcome = { kind: "session"; session: CheckoutSession } | { kind: "none" } | { kind: "uncertain"; reviewCode?: string };

/**
 * Sends the saved request (first send, or identical replay). For a key it
 * already ran, Stripe answers with the ORIGINAL response (the session as it
 * was at creation), so a replay is followed by a re-read of its current state.
 */
async function sendStoredRequest(stripe: StripeAccess, orderId: string, request: StoredPaymentRequest, now: Date, replay: boolean): Promise<SendOutcome> {
  let session: CheckoutSession;
  try {
    session = await stripe.client.createCheckoutSession(toSessionInput(orderId, request));
  } catch (error) {
    logStripeError(replay ? "checkout_payment_replay_failed" : "checkout_payment_create_failed", error);
    if (noSessionProven(error, request, now)) return { kind: "none" };
    return now.getTime() - request.storedAtMs >= KEY_RETENTION_MS ? { kind: "uncertain", reviewCode: "payment_outcome_unknown" } : { kind: "uncertain" };
  }
  if (replay) {
    try {
      session = await stripe.client.getCheckoutSession(session.id);
    } catch (error) {
      // The session is known: it is attached all the same, its state comes later.
      logStripeError("checkout_payment_reread_failed", error);
    }
  }
  return { kind: "session", session };
}

/**
 * The request can no longer lead to a payment only when ALL of these hold:
 * - its expires_at has passed: a session made by it can no longer be paid;
 * - Stripe refused the identical replay as a plain request error: it holds
 *   no result for this key, so the first send created no session (a session
 *   would have been replayed; a network cut, 5xx, 409 or 429 proves nothing);
 * - the key is still inside Stripe's retention window, so that refusal is
 *   about this key and not about a key Stripe has already forgotten.
 * Neither the date nor a refusal of the date is enough on its own.
 */
function noSessionProven(error: unknown, request: StoredPaymentRequest, now: Date): boolean {
  return (
    error instanceof StripeError &&
    error.category === "invalid_request" &&
    error.detail?.type !== "idempotency_error" &&
    Math.floor(now.getTime() / 1000) > request.expiresAt &&
    now.getTime() - request.storedAtMs < KEY_RETENTION_MS
  );
}

/** Sweep side of the same rule, for a draft whose customer never came back. */
async function resolveDraft(stripe: StripeAccess, orderId: string, request: StoredPaymentRequest, now: Date): Promise<DraftResolution> {
  const outcome = await sendStoredRequest(stripe, orderId, request, now, true);
  if (outcome.kind !== "session") return outcome;
  const s = outcome.session;
  if (s.orderId !== orderId) {
    logEvent("checkout_session_mismatch");
    return { kind: "uncertain", reviewCode: "payment_id_mismatch" };
  }
  return { kind: "session", payment: s };
}

/**
 * One Stripe line per order line, priced by the server. The personalisation
 * text is never sent to Stripe. If the unit price times the quantity does
 * not give the line total, the line is sent as one unit at its total.
 */
function toCheckoutLine(line: OrderLineSnapshot): CheckoutLine {
  const name = [line.productName, line.variantName].filter(Boolean).join(" - ").slice(0, 250) || line.sku;
  return line.unitPriceCents * line.quantity === line.lineTotalCents
    ? { name, unitAmountCents: line.unitPriceCents, quantity: line.quantity }
    : { name: `${name} x ${line.quantity}`, unitAmountCents: line.lineTotalCents, quantity: 1 };
}

export type ReturnState = "paid" | "pending" | "failed" | "cancelled" | "expired" | "refunded" | "unknown";

/**
 * State shown on /commande/retour. The session is re-read at Stripe first
 * (the browser return proves nothing), then the stored state is shown.
 */
export async function refreshOrderState(orderId: string, stripe: StripeAccess | null, now = new Date()): Promise<ReturnState> {
  const order = await getOrder(orderId);
  if (!order) return "unknown";
  if (order.paymentRef && stripe && order.paymentStatus === "awaiting_payment") {
    try {
      const session = await stripe.client.getCheckoutSession(order.paymentRef);
      if (session.orderId === orderId) {
        await applyPaymentState(orderId, session, "return_page", now);
        await notifyOrder(orderId, now);
      }
    } catch (error) {
      logStripeError("return_payment_reread_failed", error);
    }
  }
  const status = (await getOrder(orderId))?.paymentStatus;
  switch (status) {
    case "paid":
      return "paid";
    case "partially_refunded":
    case "refunded":
      return "refunded";
    case "failed":
      return "failed";
    case "cancelled":
      return "cancelled";
    case "expired":
      return "expired";
    case "draft":
    case "awaiting_payment":
      return "pending";
    default:
      return "unknown";
  }
}

/**
 * Stripe webhook. The signature is checked on the raw body first; then only
 * the event type and the session reference are read, and the session is
 * re-read at Stripe before anything is applied. Returns the HTTP status:
 * 400 for a bad signature, 200 for an ignored event or an unknown session
 * (nothing to retry), 500 when Stripe or Firestore is unavailable so Stripe
 * retries later, 503 when the webhook is not configured.
 */
export async function handleStripeWebhook(raw: string, signature: string | null, stripe: StripeAccess | null, secret: string | null, now = new Date()): Promise<number> {
  if (!stripe || !secret) {
    logEvent("stripe_webhook_unconfigured");
    return 503;
  }
  if (!verifyStripeSignature(raw, signature, secret, Math.floor(now.getTime() / 1000))) {
    logEvent("stripe_webhook_bad_signature");
    return 400;
  }
  const event = parseStripeEvent(raw);
  if (event.kind === "ignored") {
    logEvent("stripe_webhook_ignored", { reason: "event_type" });
    return 200;
  }
  // Mail Club (Stripe Billing): its own flow, see subscriptions/service.ts.
  if (event.kind === "subscription" || event.kind === "invoice") {
    if (!stripe.subscriptions) {
      logEvent("stripe_webhook_unconfigured", { reason: "subscriptions" });
      return 503;
    }
    // A TEST event (livemode false) is only handled with a test key, a real one with a live key.
    if (event.livemode !== (stripe.mode === "live")) {
      logEvent("stripe_webhook_ignored", { reason: "mode_mismatch" });
      return 200;
    }
    return handleSubscriptionEvent(event, stripe.subscriptions, now);
  }

  let session: PaymentView;
  try {
    let sessionId: string | null = event.kind === "session" ? event.sessionId : await stripe.client.findSessionIdByPaymentIntent(event.paymentIntentId);
    if (!isCheckoutSessionId(sessionId)) sessionId = null;
    if (!sessionId) {
      logEvent("stripe_webhook_ignored", { reason: "no_session" });
      return 200;
    }
    session = await stripe.client.getCheckoutSession(sessionId);
  } catch (error) {
    logStripeError("stripe_webhook_reread_failed", error);
    if (error instanceof StripeError && error.category === "not_found") return 200;
    return 500;
  }
  if (!session.orderId) {
    logEvent("stripe_webhook_ignored", { reason: "no_order" });
    return 200;
  }
  try {
    // A session whose creation response was lost: the order is still a draft
    // without payment. Only this server creates sessions carrying an orderId
    // (from the request saved with that order), so it is attached first.
    const target = await getOrder(session.orderId);
    if (target && target.paymentStatus === "draft" && !target.paymentRef) await attachPayment(session.orderId, session.id, now);
    const result = await applyPaymentState(session.orderId, session, "stripe_webhook", now);
    logEvent("stripe_webhook", { result: result.kind, ...(result.kind === "updated" ? { to: result.to } : {}), ...(result.kind === "anomaly" ? { code: result.code } : {}) });
    // E-mails due for the new state (confirmation, refund), each sent once. Never throws.
    if (result.kind !== "not_found") await notifyOrder(session.orderId, now);
    return 200;
  } catch (error) {
    logEvent("stripe_webhook_failed", { error: errorCode(error), category: errorCategory(error) });
    return 500;
  }
}
