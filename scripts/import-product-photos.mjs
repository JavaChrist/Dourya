// Imports the product photo folders (one folder = one gallery) into
// public/images/products/<category>/<slug>/NN.webp and writes
// src/data/product-galleries.generated.ts (paths, sizes, order).
//
//   node scripts/import-product-photos.mjs "C:\path\to\PHOTOS"
//
// Originals are never modified. EXIF orientation is applied, then every
// metadata block (GPS, device, dates) is dropped. Photos keep the file-name
// order: the first one is the proposed main photo, to validate.
// Uses sharp, already installed with Next (no new dependency).

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/import-product-photos.mjs <PHOTOS folder>");
  process.exit(2);
}

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public", "images", "products");
const MAX = 2000;
const IMAGE = /\.(jpe?g|png|webp)$/i;

/** Top-level folder -> shop category and kind. A folder without sub-folders is itself one gallery. */
const RUBRIQUES = {
  HEADBANDS: { category: "headbands", kind: "headband" },
  "MAIL CLUB": { category: null, kind: "mail-club" },
  PORTECLES: { category: "porte-cles", kind: "porte-cles" },
  PRINTS: { category: "prints", kind: "print" },
  "STICKER PACK": { category: "stickers", kind: "sticker-pack" },
  "STICKERS UNITE": { category: "stickers", kind: "sticker" },
};

const slugify = (s) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const byName = (a, b) => a.localeCompare(b, "en", { numeric: true });

async function entries(dir) {
  const list = await readdir(dir, { withFileTypes: true });
  return {
    dirs: list.filter((e) => e.isDirectory()).map((e) => e.name).sort(byName),
    files: list.filter((e) => e.isFile() && IMAGE.test(e.name)).map((e) => e.name).sort(byName),
  };
}

const galleries = [];
for (const rubrique of (await entries(source)).dirs) {
  const meta = RUBRIQUES[rubrique];
  if (!meta) {
    console.error(`unknown folder, skipped: ${rubrique}`);
    continue;
  }
  const top = await entries(path.join(source, rubrique));
  const folders = top.dirs.length ? top.dirs.map((d) => [d, path.join(source, rubrique, d)]) : [[rubrique, path.join(source, rubrique)]];
  for (const [folder, dir] of folders) {
    // "PACK BOOKISH" -> sticker-pack-bookish, "LALA" -> porte-cles-lala, "HEADBAND 1" -> headband-1.
    const base = meta.kind === "sticker-pack" ? slugify(folder).replace(/^pack-/, "") : slugify(folder);
    const slug = base.startsWith(meta.kind) ? base : `${meta.kind}-${base}`;
    galleries.push({ rubrique, folder, slug, category: meta.category, kind: meta.kind, dir, files: (await entries(dir)).files });
  }
}

await rm(OUT, { recursive: true, force: true });
let count = 0;
let bytes = 0;
const out = [];
for (const g of galleries) {
  const rel = path.posix.join("images", "products", g.category ?? g.kind, g.slug);
  await mkdir(path.join(ROOT, "public", rel), { recursive: true });
  const images = [];
  for (const [i, file] of g.files.entries()) {
    const name = `${String(i + 1).padStart(2, "0")}.webp`;
    const info = await sharp(path.join(g.dir, file))
      .rotate()
      .resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile(path.join(ROOT, "public", rel, name));
    images.push({ src: `/${rel}/${name}`, width: info.width, height: info.height, original: file });
    count += 1;
    bytes += info.size;
  }
  out.push({ slug: g.slug, folder: g.folder, rubrique: g.rubrique, category: g.category, kind: g.kind, images });
  console.log(`${g.slug.padEnd(34)} ${String(images.length).padStart(2)} photos  main: ${images[0]?.original ?? "-"}`);
}

const header = `// GENERATED by scripts/import-product-photos.mjs: do not edit by hand.
// One entry per photo folder. images[0] is the PROPOSED main photo (first file
// name), to be validated with Lizzie. \`original\` = source file name, for review.

export type GalleryImage = { src: string; width: number; height: number; original: string };
export type PhotoGallery = { slug: string; folder: string; rubrique: string; category: string | null; kind: string; images: GalleryImage[] };

export const photoGalleries: PhotoGallery[] = `;
await writeFile(path.join(ROOT, "src", "data", "product-galleries.generated.ts"), `${header}${JSON.stringify(out, null, 2)};\n`);
console.log(`galleries: ${out.length}, photos: ${count}, total: ${(bytes / 1024 / 1024).toFixed(1)} MB`);
